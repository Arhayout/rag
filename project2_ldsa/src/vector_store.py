"""FAISS vector store for Moroccan legal document search."""

from __future__ import annotations

import logging
from pathlib import Path

from langchain_community.vectorstores import FAISS
from langchain_core.documents import Document

from src.config import VECTOR_STORE_DIR
from src.embeddings import get_embeddings
from src.summarizer import generate_summary

logger = logging.getLogger(__name__)


class LegalDocumentStore:
    """Build, persist, load, and query a FAISS index."""

    def __init__(self, vecstore_path: str | Path = VECTOR_STORE_DIR) -> None:
        self.vectorstore_path = Path(vecstore_path)
        self.embeddings = get_embeddings()

    def generate_summary(self, document: str) -> str:
        return generate_summary(document)

    def create_summary_documents(self, documents: list[Document]) -> list[Document]:
        return [
            Document(
                page_content=self.generate_summary(document.page_content),
                metadata={
                    **document.metadata,
                    "full_content": document.page_content,
                },
            )
            for document in documents
        ]

    def save_index(self, documents: list[Document]) -> FAISS:
        if not documents:
            raise ValueError("Cannot build an index from an empty document list")

        vectorstore = FAISS.from_documents(
            self.create_summary_documents(documents), self.embeddings
        )
        self.vectorstore_path.mkdir(parents=True, exist_ok=True)
        vectorstore.save_local(str(self.vectorstore_path))
        logger.info("Saved vector index to %s", self.vectorstore_path)
        return vectorstore

    @classmethod
    def load_local(cls, vecstore_path: str | Path = VECTOR_STORE_DIR) -> FAISS | None:
        path = Path(vecstore_path)
        if not (path / "index.faiss").is_file() or not (path / "index.pkl").is_file():
            return None

        store = cls(path)
        # Only load indexes generated by this application; FAISS metadata uses pickle.
        return FAISS.load_local(
            str(path),
            store.embeddings,
            allow_dangerous_deserialization=True,
        )

    @staticmethod
    def query_similar(vectorstore: FAISS, query: str, k: int) -> list[Document]:
        if not query.strip():
            raise ValueError("Query must not be empty")
        if k < 1:
            raise ValueError("k must be at least 1")
        return vectorstore.similarity_search(query, k=k)
